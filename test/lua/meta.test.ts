// Checks the committed meta/ files: valid Lua (luaparse), headers, and
// consistency with meta/libraries.json. When the engine sources are
// available, also checks that regenerating gives the same output.
import { test } from "node:test";
import assert from "node:assert/strict";
import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import { pathToFileURL } from "node:url";
import * as luaparse from "luaparse";

const extDir = path.resolve(__dirname, "..", "..");
const metaDir = path.join(extDir, "meta");

function luaFiles(dir: string): string[] {
    return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
        const p = path.join(dir, e.name);
        if (e.isDirectory()) return luaFiles(p);
        return e.name.endsWith(".lua") ? [p] : [];
    });
}

test("meta files exist", () => {
    const files = luaFiles(metaDir).map((f) => path.relative(metaDir, f).replace(/\\/g, "/"));
    for (const f of ["_aliases.lua", "stdlib_ext.lua", "classes.lua", "generator.lua", "block.lua", "world.lua", "gfx.lua"]) {
        assert.ok(files.includes(f), `missing meta/${f}`);
    }
});

test("every meta file parses with luaparse", () => {
    for (const file of luaFiles(metaDir)) {
        const src = fs.readFileSync(file, "utf8");
        assert.doesNotThrow(
            () => luaparse.parse(src, { luaVersion: "LuaJIT", comments: false }),
            (err: Error) => {
                assert.fail(`${path.relative(metaDir, file)}: ${err.message}`);
            }
        );
        assert.match(src, /^---@meta/, `${file}: missing ---@meta`);
        assert.match(src, /generated by tools\/gen-lua-meta\.mjs/);
    }
});

test("libraries.json matches the meta files", () => {
    const json = JSON.parse(fs.readFileSync(path.join(metaDir, "libraries.json"), "utf8")) as {
        libraries: Record<string, { functions: string[]; source: string; states: string[] }>;
    };
    const libs = json.libraries;
    assert.ok(Object.keys(libs).length > 40);
    for (const lib of ["block", "world", "entities", "gfx.particles", "gfx.text3d", "events", "table", "vec3", "app"]) {
        assert.ok(libs[lib], `libraries.json lacks ${lib}`);
        assert.ok(["doc", "cpp", "both"].includes(libs[lib].source));
    }
    assert.ok(libs.block.functions.includes("set"));
    assert.ok(libs.block.states.includes("generator"));
    assert.ok(!libs.world.states.includes("generator"));
    const all = luaFiles(metaDir).map((f) => fs.readFileSync(f, "utf8")).join("\n");
    for (const [lib, info] of Object.entries(libs)) {
        if (lib.includes(":") || lib === "_G") continue;
        for (const fn of info.functions) {
            assert.ok(all.includes(`function ${lib}.${fn}(`), `${lib}.${fn} missing in meta`);
        }
    }
});

test("generator is deterministic and up to date", async (t) => {
    const root = process.env.VOXELCORE_ROOT ?? path.resolve(extDir, "..");
    if (!fs.existsSync(path.join(root, "doc", "en", "scripting"))) {
        t.skip("engine sources not available");
        return;
    }
    const genPath: string = path.join(extDir, "tools", "gen-lua-meta.mjs");
    const gen = (await import(pathToFileURL(genPath).href)) as {
        generate(cfg: { root: string; out: string; log?: (s: string) => void }): { files: string[] };
    };
    const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "vc-meta-"));
    try {
        const outA = path.join(tmp, "a");
        const outB = path.join(tmp, "b");
        gen.generate({ root, out: outA, log: () => {} });
        gen.generate({ root, out: outB, log: () => {} });
        for (const f of [...luaFiles(outA), path.join(outA, "libraries.json")]) {
            const rel = path.relative(outA, f);
            const a = fs.readFileSync(f, "utf8");
            assert.equal(a, fs.readFileSync(path.join(outB, rel), "utf8"), `${rel} is not deterministic`);
            assert.equal(a, fs.readFileSync(path.join(metaDir, rel), "utf8"), `meta/${rel} is stale: run npm run gen`);
        }
    } finally {
        fs.rmSync(tmp, { recursive: true, force: true });
    }
});

