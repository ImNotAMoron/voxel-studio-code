import { test } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { quickWorldScript, syncPackLinks } from "../../src/run/userdir";

const engineRoot = path.resolve(__dirname, "../../..");
const exe = path.join(engineRoot, "build/Debug", process.platform === "win32" ? "VoxelCore.exe" : "VoxelCore");

function tmp(name: string) {
    return fs.mkdtempSync(path.join(os.tmpdir(), `vc-${name}-`));
}

test("syncPackLinks links, keeps, replaces and removes only links", () => {
    const dir = tmp("links");
    const packA = path.join(dir, "src", "a");
    const packB = path.join(dir, "src", "b");
    fs.mkdirSync(packA, { recursive: true });
    fs.mkdirSync(packB, { recursive: true });
    fs.writeFileSync(path.join(packA, "package.json"), "{}");
    const userDir = path.join(dir, "user");
    fs.mkdirSync(path.join(userDir, "content", "real"), { recursive: true });

    let report = syncPackLinks(userDir, [{ id: "a", root: packA }, { id: "real", root: packB }]);
    assert.deepEqual(report.linked, ["a"]);
    assert.deepEqual(report.blocked, ["real"]);
    assert.ok(fs.existsSync(path.join(userDir, "content", "a", "package.json")));

    report = syncPackLinks(userDir, [{ id: "a", root: packA }]);
    assert.deepEqual(report.unchanged, ["a"]);

    // retarget a -> b
    report = syncPackLinks(userDir, [{ id: "a", root: packB }]);
    assert.deepEqual(report.linked, ["a"]);
    assert.ok(!fs.existsSync(path.join(userDir, "content", "a", "package.json")));

    report = syncPackLinks(userDir, []);
    assert.deepEqual(report.removed, ["a"]);
    assert.ok(fs.existsSync(path.join(userDir, "content", "real")), "real folders are never removed");
    assert.ok(fs.existsSync(packB), "link removal must not delete the target");
});

test("quick world script opens a world with a linked pack (real engine, headless)", { skip: !fs.existsSync(exe) && "engine not built" }, () => {
    const dir = tmp("engine");
    const userDir = path.join(dir, "user");
    syncPackLinks(userDir, [{ id: "backrooms", root: path.join(engineRoot, "packs", "backrooms") }]);
    const script = path.join(dir, "quick_world.lua");
    const body = quickWorldScript({
        world: "vscode-dev",
        seed: "1",
        generator: "backrooms:level0",
        packs: ["backrooms"],
        recreate: false,
    });
    // headless check: print state, then close cleanly
    fs.writeFileSync(
        script,
        body +
            [
                "assert(world.is_open())",
                'print("generator=" .. world.get_generator())',
                'print("content=" .. table.concat(app.get_content(), ","))',
                "app.close_world(true)",
                "",
            ].join("\n")
    );
    const run = () =>
        spawnSync(exe, ["--headless", "--script", script, "--res", path.join(engineRoot, "res"), "--dir", userDir], {
            cwd: path.dirname(exe),
            encoding: "utf8",
            timeout: 120_000,
        });
    let result = run();
    assert.equal(result.status, 0, result.stdout + result.stderr);
    assert.match(result.stdout, /generator=backrooms:level0/);
    assert.match(result.stdout, /content=.*backrooms/);
    // second run reopens the existing world
    result = run();
    assert.equal(result.status, 0, result.stdout + result.stderr);
    assert.match(result.stdout, /generator=backrooms:level0/);
});

test("a pack generated by the scaffold templates loads in the engine", { skip: !fs.existsSync(exe) && "engine not built" }, async () => {
    const t = await import("../../src/scaffold/templates");
    const dir = tmp("scaffold");
    const pack = path.join(dir, "scaffold_test");
    const write = (rel: string, content: string | Buffer) => {
        fs.mkdirSync(path.dirname(path.join(pack, rel)), { recursive: true });
        fs.writeFileSync(path.join(pack, rel), content);
    };
    write("package.json", t.packageJson({ id: "scaffold_test", title: "T", creator: "c", description: "", dependencies: ["base"] }));
    write("icon.png", t.placeholderPng("scaffold_test", 128));
    for (const kind of ["basic", "faces", "model", "light"] as const) {
        const name = `b_${kind}`;
        write(`blocks/${name}.json`, t.blockJson(name, kind, true));
        for (const tex of t.blockTextureNames(name, kind)) write(`textures/blocks/${tex}.png`, t.placeholderPng(tex));
        if (kind === "model") write(`models/${name}.vcm`, t.blockModelVcm(name));
    }
    write("scripts/b_basic.lua", t.blockScript());
    write("items/thing.json", t.itemJson("thing"));
    write("textures/items/thing.png", t.placeholderPng("thing"));
    write("scripts/thing.lua", t.itemScript());
    write("entities/mob.json", t.entityJson("scaffold_test", "mob"));
    write("scripts/components/mob.lua", t.componentScript());
    write("scripts/world.lua", t.worldScript());

    const userDir = path.join(dir, "user");
    syncPackLinks(userDir, [{ id: "scaffold_test", root: pack }]);
    const script = path.join(dir, "check.lua");
    fs.writeFileSync(
        script,
        quickWorldScript({ world: "w", seed: "1", generator: "base:flat_grass", packs: ["scaffold_test"], recreate: true }) +
            [
                'for _, n in ipairs({"b_basic", "b_faces", "b_model", "b_light"}) do',
                '    assert(block.index("scaffold_test:" .. n), n)',
                "end",
                'assert(item.index("scaffold_test:thing"))',
                'assert(item.index("scaffold_test:b_basic.item"))',
                'local e = entities.spawn("scaffold_test:mob", {0, 100, 0})',
                "assert(e)",
                'print("scaffold-ok")',
                "app.close_world(true)",
                "",
            ].join("\n")
    );
    const result = spawnSync(exe, ["--headless", "--script", script, "--res", path.join(engineRoot, "res"), "--dir", userDir], {
        cwd: path.dirname(exe),
        encoding: "utf8",
        timeout: 120_000,
    });
    assert.equal(result.status, 0, result.stdout + result.stderr);
    assert.match(result.stdout, /scaffold-ok/);
    const log = fs.readFileSync(path.join(userDir, "latest.log"), "utf8");
    const problems = log.split(/\r?\n/).filter((l) => /^\[(E|W)\]/.test(l));
    assert.deepEqual(problems, [], "engine log has errors or warnings");
});
