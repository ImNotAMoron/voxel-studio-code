function splitTopLevel(text, separators) {
    const parts = [];
    let depth = 0;
    let current = "";
    let quote = "";
    for (let i = 0; i < text.length; i++) {
        const c = text[i];
        if (quote) {
            current += c;
            if (c === quote) quote = "";
            continue;
        }
        if (c === '"' || c === "'") {
            quote = c;
            current += c;
            continue;
        }
        const arrow = c === ">" && text[i - 1] === "-"; // `->` in types
        if ("([{<".includes(c)) depth++;
        if (")]}>".includes(c) && depth > 0 && !arrow) depth--;
        if (depth === 0 && separators.includes(c)) {
            parts.push(current);
            current = "";
            continue;
        }
        current += c;
    }
    parts.push(current);
    return parts.map((p) => p.trim()).filter((p) => p.length > 0);
}

/**
 * Maps a documentation type expression to a LuaLS type.
 * @param {string} raw
 * @param {{vecn?: string}} [ctx]
 */
export function mapType(raw, ctx = {}) {
    let text = (raw ?? "").trim();
    if (!text) return "any";
    // strip trailing descriptions such as `int # comment`
    text = text.replace(/\s+#.*$/, "").trim();
    if (/^function\b/.test(text)) return "function";
    if (/^fun\(/.test(text)) return text;
    const braced = /^(\w+)\s*\{[\s\S]*\}$/.exec(text);
    if (braced) return mapType(braced[1], ctx);
    const unionParts = splitTopLevel(text.replace(/\s+or\s+/g, "|"), ["|"]);
    if (unionParts.length > 1) {
        const mapped = [...new Set(unionParts.map((p) => mapType(p, ctx)))];
        if (mapped.includes("any")) return "any";
        return mapped.join("|");
    }
    if (text.startsWith("{") && text.endsWith("}")) {
        const inner = text.slice(1, -1).trim();
        if (!inner) return "table";
        const items = splitTopLevel(inner, [","]);
        if (items.every((i) => /^[A-Za-z_]\w*\s*:/.test(i))) {
            const fields = items.map((i) => {
                const idx = i.indexOf(":");
                return `${i.slice(0, idx).trim()}: ${mapType(i.slice(idx + 1), ctx)}`;
            });
            return `{ ${fields.join(", ")} }`;
        }
        const types = [...new Set(items.map((i) => mapType(i, ctx)))];
        if (types.length === 1 && types[0] !== "any" && !types[0].includes("|")) {
            return `${types[0]}[]`;
        }
        return "table";
    }
    let m = /^array of (\w+)$/.exec(text);
    if (m) return `${mapType(m[1].replace(/s$/, ""), ctx)}[]`;
    m = /^(\w+?)s?\s+array\b/.exec(text);
    if (m) return `${mapType(m[1], ctx)}[]`;
    if (/^table of\b/.test(text)) return "table";
    m = /^table<(.*)>$/.exec(text);
    if (m) {
        const args = splitTopLevel(m[1], [","]).map((a) => mapType(a, ctx));
        if (args.length === 1) return `${args[0]}[]`;
        if (args.length === 2) return `table<${args[0]}, ${args[1]}>`;
        return "table";
    }
    m = /^(.+)\[\]$/.exec(text);
    if (m) {
        const inner = mapType(m[1], ctx);
        return inner === "any" ? "any[]" : `${inner}[]`;
    }
    if (text.endsWith("?")) {
        const inner = mapType(text.slice(0, -1), ctx);
        return inner === "any" ? "any" : `${inner}|nil`;
    }
    if (text === "vector" && ctx.vecn) return ctx.vecn;
    if (Object.hasOwn(TYPE_ALIASES, text)) return text;
    const lower = text.toLowerCase();
    if (Object.hasOwn(SIMPLE_TYPES, text)) return SIMPLE_TYPES[text];
    if (Object.hasOwn(SIMPLE_TYPES, lower)) return SIMPLE_TYPES[lower];
    if (CLASS_NAMES.has(text)) return text;
    if (lower === "xml") return "XML";
    return "any";
}

