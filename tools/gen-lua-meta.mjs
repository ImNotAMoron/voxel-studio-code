function rootNote(r, cppLibs) {
    const info = cppLibs.get(r);
    if (!info) return [`Library \`${r}\` (composed in Lua).`];
    if (info.states.includes("generator")) return [`Library \`${r}\`: available in all Lua states, including world generators.`];
    if (info.states.includes("client")) return [`Library \`${r}\`: client only (opened with the HUD).`];
    return [`Library \`${r}\`: not available in world generator scripts.`];
}

