/**
 * @typedef {{name: string, type: string, optional: boolean, desc: string}} Param
 * @typedef {{type: string}} Ret
 * @typedef {{
 *   kind: "function"|"field",
 *   path: string[],
 *   sep: "."|":",
 *   name: string,
 *   params: Param[],
 *   returns: Ret[],
 *   fieldType?: string,
 *   desc: string[],
 *   file: string,
 * }} DocEntry
 */

const PATH_RE = /^([A-Za-z_]\w*(?:[.:][A-Za-z_]\w*)*)/;
const IDENT_RE = /^[A-Za-z_]\w*$/;

function stripLineComment(line) {
    // `-- comment` that is not an arrow `-->`
    const m = /(^|\s)--(?!>)(.*)$/.exec(line);
    if (!m) return { code: line, comment: "" };
    return {
        code: line.slice(0, m.index + m[1].length),
        comment: m[2].replace(/^-*\s?/, "").trim(),
    };
}

/**
 * Parses one parameter token.
 * @returns {Param | null} null when the token is a literal (example code)
 */
export function parseParam(token, index, opts = {}) {
    let text = token.trim();
    let optional = false;
    if (/^\[optional\]\s*/i.test(text)) {
        optional = true;
        text = text.replace(/^\[optional\]\s*/i, "");
    }
    if (/^\[.*\]$/.test(text)) {
        optional = true;
        text = text.slice(1, -1).trim();
    }
    if (text === "..." || /^\w+\.\.\.$/.test(text) || text.startsWith("...")) {
        const colon = text.indexOf(":");
        const type = colon >= 0 ? mapType(text.slice(colon + 1), opts) : "any";
        return { name: "...", type, optional: false, desc: "" };
    }
    let name = text;
    let type = "any";
    let typeText = "";
    const eq = findTopLevel(text, "=");
    if (eq >= 0) {
        optional = true;
        name = text.slice(0, eq).trim();
    }
    const colon = findTopLevel(name, ":");
    if (colon >= 0) {
        typeText = name.slice(colon + 1).trim();
        name = name.slice(0, colon).trim();
        if (name.endsWith("?")) {
            optional = true;
            name = name.slice(0, -1);
        }
        // core: module docs write `integer: byte`, `string: str` (type first)
        if (opts.swapTypeAndName && SWAPPED_TYPE_WORDS.has(name)) {
            [name, typeText] = [typeText, name];
        }
        type = mapType(typeText, opts);
    }
    if (!IDENT_RE.test(name)) {
        // `table|ByteArray|str` - a bare type without a name
        if (colon < 0 && /^[A-Za-z_][\w|<>\[\], ]*$/.test(name)) {
            const mapped = mapType(name, opts);
            if (mapped === "any") return null;
            return { name: `arg${index + 1}`, type: mapped, optional, desc: "" };
        }
        return colon >= 0 && /^[\w\s|]+$/.test(name)
            ? { name: `arg${index + 1}`, type, optional, desc: "" }
            : null;
    }
    if (LUA_RESERVED.has(name)) name = `${name}_`;
    return { name, type, optional, desc: "" };
}

function findTopLevel(text, ch) {
    let depth = 0;
    for (let i = 0; i < text.length; i++) {
        const c = text[i];
        if ("([{<".includes(c)) depth++;
        else if (")]}>".includes(c)) depth--;
        else if (c === ch && depth === 0) return i;
    }
    return -1;
}

function bracketBalance(text) {
    let depth = 0;
    let quote = "";
    for (const c of text) {
        if (quote) {
            if (c === quote) quote = "";
        } else if (c === '"' || c === "'") quote = c;
        else if (c === "(" || c === "{") depth++;
        else if (c === ")" || c === "}") depth--;
    }
    return depth;
}

/**
 * `face1, face2, ..., face6` → face1..face6; other non-trailing `...` are
 * dropped (a vararg must be the last parameter in Lua).
 * @param {Param[]} params
 */
function fixInnerVarargs(params) {
    for (let i = params.length - 2; i >= 0; i--) {
        if (params[i].name !== "...") continue;
        const prev = /^(.*?)(\d+)$/.exec(params[i - 1]?.name ?? "");
        const next = /^(.*?)(\d+)$/.exec(params[i + 1].name);
        const fill = [];
        if (prev && next && prev[1] === next[1]) {
            for (let n = Number(prev[2]) + 1; n < Number(next[2]); n++) {
                fill.push({ ...params[i - 1], name: `${prev[1]}${n}`, desc: "" });
            }
        }
        params.splice(i, 1, ...fill);
    }
}

/**
 * Parses the signature starting at `lines[start]`.
 * @returns {{entry?: Omit<DocEntry, "file"|"desc">, consumed: number, reason?: string}}
 */
export function parseSignature(lines, start, opts = {}) {
    let first = lines[start].trim();
    first = first.replace(/^local\s+[A-Za-z_]\w*\s*=\s*/, "");
    first = first.replace(/^function\s+/, "");
    const pm = PATH_RE.exec(first);
    if (!pm) return { consumed: 1, reason: "no path" };
    const fullPath = pm[1];
    let rest = first.slice(fullPath.length);
    const colonIdx = fullPath.lastIndexOf(":");
    const sep = colonIdx >= 0 ? ":" : ".";
    const segs = colonIdx >= 0
        ? [...fullPath.slice(0, colonIdx).split("."), fullPath.slice(colonIdx + 1)]
        : fullPath.split(".");
    const name = segs[segs.length - 1];
    const owner = segs.slice(0, -1);

    const fieldMatch = /^\s*(?::\s*|-+>\s*)(.+)$/.exec(rest);
    if (!rest.trimStart().startsWith("(")) {
        if (fieldMatch && sep === ".") {
            return {
                entry: {
                    kind: "field", path: owner, sep, name, params: [], returns: [],
                    fieldType: mapType(stripLineComment(fieldMatch[1]).code, opts),
                },
                consumed: 1,
            };
        }
        return { consumed: 1, reason: "not a signature" };
    }

    // collect the parameter list (may span lines)
    const argLines = [];
    let consumed = 1;
    let text = rest.trimStart().slice(1);
    let depth = 1;
    let afterParen = "";
    for (;;) {
        let closed = false;
        let quote = "";
        let i = 0;
        const { code } = stripLineComment(text);
        for (; i < text.length; i++) {
            const c = text[i];
            if (i >= code.length) break; // comment part
            if (quote) {
                if (c === quote) quote = "";
                continue;
            }
            if (c === '"' || c === "'") quote = c;
            else if (c === "(" || c === "{" || c === "[") depth++;
            else if (c === ")" || c === "}" || c === "]") {
                depth--;
                if (depth === 0) {
                    closed = true;
                    break;
                }
            }
        }
        if (closed) {
            argLines.push(text.slice(0, i));
            afterParen = text.slice(i + 1);
            break;
        }
        argLines.push(text);
        if (start + consumed >= lines.length) {
            return { consumed, reason: "unbalanced parentheses" };
        }
        text = lines[start + consumed];
        consumed++;
    }

    // parameters
    /** @type {Param[]} */
    const params = [];
    let pendingDesc = [];
    let pendingOptional = false;
    // join lines of a table type spanning several lines: `params: table {`
    const joined = [];
    for (let k = 0; k < argLines.length; k++) {
        let line = argLines[k];
        let { code } = stripLineComment(line);
        while (bracketBalance(code) > 0 && k + 1 < argLines.length) {
            k++;
            code += " " + stripLineComment(argLines[k]).code.trim();
            line = code;
        }
        joined.push(line);
    }
    for (const line of joined) {
        const { code, comment } = stripLineComment(line);
        if (!code.trim()) {
            if (comment) {
                if (/\[optional\]/i.test(comment)) pendingOptional = true;
                const cleaned = comment.replace(/\[optional\]\s*/i, "").trim();
                if (cleaned) pendingDesc.push(cleaned);
            }
            continue;
        }
        for (const token of splitTopLevel(code, [","])) {
            if (/^\[optional\]$/i.test(token)) {
                pendingOptional = true;
                continue;
            }
            const p = parseParam(token, params.length, opts);
            if (!p) {
                return { consumed, reason: `literal argument \`${token}\`` };
            }
            if (pendingOptional) p.optional = true;
            p.desc = [...pendingDesc, comment].filter(Boolean).join(" ");
            pendingDesc = [];
            pendingOptional = false;
            comment && (pendingDesc = []);
            params.push(p);
        }
    }
    fixInnerVarargs(params);

    // return part
    /** @type {Ret[]} */
    let returns = [];
    let retText = "";
    const rm = /^\s*-*>\s*(.*)$/.exec(afterParen);
    if (rm) {
        retText = rm[1];
        while (bracketBalance(retText) > 0 && start + consumed < lines.length) {
            retText += " " + lines[start + consumed].trim();
            consumed++;
        }
        retText = stripLineComment(retText).code.trim();
        if (/^\[.*\)$/.test(retText)) retText = "number"; // `--> [0..1)` ranges
        returns = splitTopLevel(retText, [","]).map((t) => ({ type: mapType(t, opts) }));
        if (returns.length === 1 && returns[0].type === "nil") returns = [];
    }
    return {
        entry: { kind: "function", path: owner, sep, name, params, returns },
        consumed,
    };
}

/** Finds a signature embedded at the end of a comment (`... . lib.f(x) -> y`). */
function embeddedSignature(comment) {
    const m = /^(.*?\.)\s+((?:[A-Za-z_]\w*[.:])*[A-Za-z_]\w*\([^()]*\)(?:\s*-+>\s*.+)?)$/.exec(comment);
    if (!m) return null;
    return { text: m[1], signature: m[2] };
}

