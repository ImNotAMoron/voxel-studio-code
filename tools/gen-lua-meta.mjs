function main() {
    const here = path.dirname(fileURLToPath(import.meta.url));
    const extDir = path.resolve(here, "..");
    const root = process.env.VOXELCORE_ROOT
        ? path.resolve(process.env.VOXELCORE_ROOT)
        : path.resolve(extDir, "..");
    if (!fs.existsSync(path.join(root, "doc", "en", "scripting"))) {
        console.error(`gen-lua-meta: VoxelCore repo not found at ${root} (set VOXELCORE_ROOT)`);
        process.exit(1);
    }
    const out = path.join(extDir, "meta");
    generate({ root, out, verbose: process.argv.includes("--verbose") });
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
    main();
}
